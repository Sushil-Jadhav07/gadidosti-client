export const INTRA_CITY_BASE = 500;
export const PER_KM_RATE = 12;
export const PLATFORM_FEE_PERCENT = 10;

export function calculatePrice(truckCategory, pickup, drop, transportType) {
  const truck = TRUCK_OPTIONS.find((t) => t.id === truckCategory);
  if (!truck) return null;

  let baseFare = truck.basePrice;
  let distance = 0;
  let distanceFare = 0;

  if (transportType === "intra") {
    distance = 25; // assume 25km for intra-city
    distanceFare = INTRA_CITY_BASE;
  } else {
    const key = `${pickup}-${drop}`;
    distance = DISTANCE_MAP[key] || 500; // fallback
    distanceFare = distance * PER_KM_RATE;
  }

  const subtotal = baseFare + distanceFare;
  const platformFee = Math.round(subtotal * (PLATFORM_FEE_PERCENT / 100));
  const total = subtotal + platformFee;

  return {
    baseFare,
    distance,
    distanceFare,
    platformFee,
    total,
    subtotal,
  };
}

export function generateBookingId() {
  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, "0");
  const random = String(Math.floor(Math.random() * 900) + 100);
  return `BKG-${year}${month}-${random}`;
}
